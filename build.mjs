// Build the standalone Windows package:   node build.mjs [--ui-only]
//   1. embed ui/index.html into lib/ui-bundle.mjs
//   2. bun build --compile  ->  dist/AndroidGuardian/AndroidGuardian.exe  (JavaScript runtime included)
//   3. put adb (platform-tools) and aapt2 next to it, taken from the local Android SDK or downloaded from Google
//   4. add installer scripts, licences, current threat list; zip the folder; write SHA256SUMS.txt
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, rmSync, readdirSync, statSync, cpSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const uiOnly = process.argv.includes('--ui-only');
const run = (cmd, args, opts = {}) => {
  const r = spawnSync(cmd, args, { stdio: 'inherit', timeout: 900_000, ...opts });
  if (r.status !== 0) throw new Error(`${cmd} ${args.join(' ')} failed (${r.status})`);
};

// 1. embed UI
const html = readFileSync(join(root, 'ui', 'index.html'), 'utf8').split('REPO_PLACEHOLDER').join(pkg.repository.replace(/^github:/, ''));
writeFileSync(join(root, 'lib', 'ui-bundle.mjs'), `// generated by build.mjs from ui/index.html - do not edit\nexport const UI_HTML = ${JSON.stringify(html)};\n`);
console.log('ui-bundle.mjs written');
if (uiOnly) process.exit(0);

const dist = join(root, 'dist', 'AndroidGuardian');
rmSync(join(root, 'dist'), { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// 2. compile
const icon = join(root, 'assets', 'icon.ico');
if (!existsSync(icon) && process.platform === 'win32') run('powershell', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', join(root, 'installer', 'make-icon.ps1')]);
const exe = join(dist, 'AndroidGuardian.exe');
const bunArgs = ['build', '--compile', '--minify', '--target=bun-windows-x64', join(root, 'guardian.mjs'), '--outfile', exe];
if (existsSync(icon)) bunArgs.push(`--windows-icon=${icon}`);
run('bun', bunArgs);

// 3. Android tools: local SDK first, else download Google's official zips into .cache/
const cache = join(root, '.cache');
mkdirSync(cache, { recursive: true });
function download(url, dest) {
  if (existsSync(dest)) return;
  console.log(`downloading ${url}`);
  run('curl', ['-fsSL', '-o', dest, url]);
}
function unzip(zip, into) {
  mkdirSync(into, { recursive: true });
  run('tar', ['-xf', zip, '-C', into]); // bsdtar on Windows 10+, macOS, Linux
}
const sdk = process.env.ANDROID_HOME || (process.env.LOCALAPPDATA ? join(process.env.LOCALAPPDATA, 'Android', 'Sdk') : '');
let pt = sdk && join(sdk, 'platform-tools');
if (!pt || !existsSync(join(pt, 'adb.exe'))) {
  download('https://dl.google.com/android/repository/platform-tools-latest-windows.zip', join(cache, 'platform-tools.zip'));
  unzip(join(cache, 'platform-tools.zip'), cache);
  pt = join(cache, 'platform-tools');
}
mkdirSync(join(dist, 'platform-tools'), { recursive: true });
for (const f of ['adb.exe', 'AdbWinApi.dll', 'AdbWinUsbApi.dll', 'libwinpthread-1.dll', 'NOTICE.txt', 'source.properties']) {
  if (existsSync(join(pt, f))) copyFileSync(join(pt, f), join(dist, 'platform-tools', f));
  else if (!f.endsWith('.txt') && !f.endsWith('.properties')) throw new Error(`platform-tools is missing ${f}`);
}
let aapt2 = null;
if (sdk && existsSync(join(sdk, 'build-tools'))) {
  const v = readdirSync(join(sdk, 'build-tools')).sort().reverse().find((d) => existsSync(join(sdk, 'build-tools', d, 'aapt2.exe')));
  if (v) aapt2 = join(sdk, 'build-tools', v, 'aapt2.exe');
}
if (!aapt2) {
  download('https://dl.google.com/android/repository/build-tools_r35_windows.zip', join(cache, 'build-tools.zip'));
  unzip(join(cache, 'build-tools.zip'), join(cache, 'build-tools'));
  const found = readdirSync(join(cache, 'build-tools')).map((d) => join(cache, 'build-tools', d, 'aapt2.exe')).find(existsSync);
  if (found) aapt2 = found;
}
if (aapt2) { mkdirSync(join(dist, 'tools'), { recursive: true }); copyFileSync(aapt2, join(dist, 'tools', 'aapt2.exe')); }
else console.warn('aapt2 not found: app display names will be missing in reports');

// 4. package extras
mkdirSync(join(dist, 'data'), { recursive: true });
if (existsSync(join(root, 'data', 'stalkerware.stix2'))) copyFileSync(join(root, 'data', 'stalkerware.stix2'), join(dist, 'data', 'stalkerware.stix2'));
for (const f of ['README.md', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'SECURITY.md']) copyFileSync(join(root, f), join(dist, f));
copyFileSync(join(root, 'installer', 'install.ps1'), join(dist, 'install.ps1'));
copyFileSync(join(root, 'installer', 'uninstall.ps1'), join(dist, 'uninstall.ps1'));
writeFileSync(join(dist, 'VERSION'), pkg.version + '\n');
writeFileSync(join(dist, 'Install.cmd'), '@echo off\r\ntitle Android Guardian setup\r\npowershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0install.ps1" -Local "%~dp0."\r\nif errorlevel 1 pause\r\n');
writeFileSync(join(dist, 'Uninstall.cmd'), '@echo off\r\ntitle Android Guardian uninstall\r\npowershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0uninstall.ps1"\r\n');

const zipName = `AndroidGuardian-win64-v${pkg.version}.zip`;
const zip = join(root, 'dist', zipName);
run('powershell', ['-NoProfile', '-Command', `Compress-Archive -Path '${dist}' -DestinationPath '${zip}' -Force`]);
const sha = createHash('sha256').update(readFileSync(zip)).digest('hex');
writeFileSync(join(root, 'dist', 'SHA256SUMS.txt'), `${sha}  ${zipName}\n`);
const size = (p) => (statSync(p).size / 1024 / 1024).toFixed(1) + ' MB';
console.log(`\nexe ${size(exe)}, zip ${size(zip)}\nsha256 ${sha}\nfolder: ${dist}`);
