// Build the standalone Windows package.
//
//   node build.mjs                  full build: dist/AndroidGuardian/ + dist/AndroidGuardian-win64-v<version>.zip + dist/SHA256SUMS.txt
//   node build.mjs --ui-only        only regenerate lib/ui-bundle.mjs (used by `npm start` / `npm run demo`)
//   node build.mjs --skip-compile   reuse the exe from the previous build (for doc-only or installer-only changes)
//   node build.mjs --pinned-tools   ignore the local Android SDK; use the pinned, checksum-verified Google zips (CI does this)
//   node build.mjs --no-iocs        do not bundle the Echap threat list (the app downloads it on first scan)
//
// Steps:
//   1. embed ui/index.html into lib/ui-bundle.mjs
//   2. bun build --compile  ->  dist/AndroidGuardian/AndroidGuardian.exe  (JavaScript runtime included)
//   3. put adb (platform-tools) and aapt2 next to it: local Android SDK, or Google's official zips (SHA-1 checked
//      against Google's own repository manifest) downloaded into .cache/
//   4. add installer scripts, licences, VERSION, the current threat list, and SHA256SUMS.txt for every file
//   5. zip it deterministically (sorted, fixed timestamps = commit time) and write dist/SHA256SUMS.txt for the zip
// Exits non-zero, with a message saying what is missing, if any piece is missing. Windows only (bun's
// --windows-icon and the bundled adb.exe are Windows things).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, rmSync, readdirSync, statSync, renameSync, utimesSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { deflateRawSync, crc32 } from 'node:zlib';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const argv = new Set(process.argv.slice(2));
const known = ['--ui-only', '--skip-compile', '--pinned-tools', '--no-iocs'];
for (const a of argv) if (!known.includes(a)) die(`unknown option ${a} (known: ${known.join(' ')})`);

// Pinned Android tools. Versions and SHA-1 come from https://dl.google.com/android/repository/repository2-3.xml
// (Google publishes SHA-1 only). To update: find the <remotePackage path="platform-tools"> / "build-tools;35.0.0"
// entries there, copy <url> and <checksum>, and run a build.
const GOOGLE = 'https://dl.google.com/android/repository/';
const PLATFORM_TOOLS = { file: 'platform-tools_r37.0.1-win.zip', sha1: 'e03e78b1d80b396f1c3358e31251cb31740e1110' };
// Note the underscore: build-tools_r35-windows.zip (hyphen) is a 404; build-tools_r35_windows.zip is the real one.
const BUILD_TOOLS = { file: 'build-tools_r35_windows.zip', sha1: 'af059bb67cf7786f45ee0db85e2d24985df1b4b6' };
const STIX_URL = 'https://raw.githubusercontent.com/AssoEchap/stalkerware-indicators/master/generated/stalkerware.stix2';

function die(msg) {
  console.error(`\nbuild failed: ${msg}`);
  process.exit(1);
}
function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: 'inherit', timeout: 900_000, ...opts });
  if (r.error) die(`${cmd} could not be started (${r.error.code || r.error.message})`);
  if (r.status !== 0) die(`${cmd} ${args.join(' ')} exited with ${r.status}`);
}
const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;
const hashFile = (algo, p) => createHash(algo).update(readFileSync(p)).digest('hex');

// ------------------------------------------------------------------ 1. embed UI
const repo = pkg.repository?.url ? pkg.repository.url.replace(/^.*github\.com\//, '').replace(/\.git$/, '') : String(pkg.repository).replace(/^github:/, '');
const html = readFileSync(join(root, 'ui', 'index.html'), 'utf8').split('REPO_PLACEHOLDER').join(repo);
writeFileSync(join(root, 'lib', 'ui-bundle.mjs'), `// generated by build.mjs from ui/index.html - do not edit\nexport const UI_HTML = ${JSON.stringify(html)};\n`);
console.log('ui-bundle.mjs written');
if (argv.has('--ui-only')) process.exit(0);

if (process.platform !== 'win32') die('the Windows package is built on Windows (use --ui-only elsewhere)');
const tar = join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe'); // bsdtar; not Git Bash's GNU tar, which cannot read zips
if (!existsSync(tar)) die(`${tar} not found (it ships with Windows 10 1803 and later)`);

const distRoot = join(root, 'dist');
const dist = join(distRoot, 'AndroidGuardian');
const exe = join(dist, 'AndroidGuardian.exe');
const cache = join(root, '.cache');
mkdirSync(cache, { recursive: true });

// --skip-compile keeps the previous exe across the clean-up below.
let keptExe = null;
if (argv.has('--skip-compile')) {
  if (!existsSync(exe)) die('--skip-compile needs a previous full build (dist/AndroidGuardian/AndroidGuardian.exe is missing)');
  keptExe = join(cache, 'AndroidGuardian.prev.exe');
  renameSync(exe, keptExe);
}
rmSync(distRoot, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// ------------------------------------------------------------------ 2. compile
if (keptExe) {
  renameSync(keptExe, exe);
  console.log('exe reused from the previous build (--skip-compile)');
} else {
  const bunV = spawnSync('bun', ['--version'], { encoding: 'utf8', timeout: 30_000 });
  if (bunV.error || bunV.status !== 0) die('Bun is not installed. Install it from https://bun.sh (Windows: powershell -c "irm bun.sh/install.ps1 | iex"), then run this again.');
  console.log(`bun ${bunV.stdout.trim()}`);
  const icon = join(root, 'assets', 'icon.ico');
  if (!existsSync(icon)) run('powershell', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', join(root, 'installer', 'make-icon.ps1')]);
  if (!existsSync(icon)) die('assets/icon.ico could not be created');
  const winVersion = `${pkg.version.replace(/[^0-9.].*$/, '')}.0`.split('.').slice(0, 4).join('.');
  // --windows-hide-console is deliberately NOT used: the console window is the app's only visible
  // "it is running" sign and its quit handle (closing it stops the local server and adb). Revisit only
  // if the UI gains its own Quit button.
  run('bun', [
    'build', '--compile', '--minify', '--target=bun-windows-x64', join(root, 'guardian.mjs'), '--outfile', exe,
    `--windows-icon=${icon}`,
    '--windows-title=Android Guardian',
    `--windows-publisher=${pkg.author}`,
    `--windows-version=${winVersion}`,
    '--windows-description=Android Guardian - find and remove spyware on an Android phone',
    `--windows-copyright=Copyright (c) 2026 ${pkg.author}. MIT licence.`,
  ]);
}
if (!existsSync(exe)) die('bun did not produce AndroidGuardian.exe');

// ------------------------------------------------------------------ 3. Android tools
async function download(url, dest, sha1) {
  if (existsSync(dest) && (!sha1 || hashFile('sha1', dest) === sha1)) return dest;
  console.log(`downloading ${url}`);
  const res = await fetch(url, { signal: AbortSignal.timeout(600_000) });
  if (!res.ok) die(`download failed: ${url} (HTTP ${res.status})`);
  const buf = Buffer.from(await res.arrayBuffer());
  const got = createHash('sha1').update(buf).digest('hex');
  if (sha1 && got !== sha1) die(`${url} has SHA-1 ${got}, expected ${sha1}. Refusing to package it.`);
  writeFileSync(dest, buf);
  return dest;
}
function unzip(zip, into) {
  rmSync(into, { recursive: true, force: true });
  mkdirSync(into, { recursive: true });
  run(tar, ['-xf', zip, '-C', into]);
}
const readProp = (file, key) => (existsSync(file) ? (readFileSync(file, 'utf8').match(new RegExp(`^${key}=(.*)$`, 'm')) || [])[1]?.trim() : undefined);

const sdk = argv.has('--pinned-tools') ? '' : process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || (process.env.LOCALAPPDATA ? join(process.env.LOCALAPPDATA, 'Android', 'Sdk') : '');
let pt = sdk && join(sdk, 'platform-tools');
let ptOrigin = `local SDK (${pt})`;
if (!pt || !existsSync(join(pt, 'adb.exe'))) {
  await download(GOOGLE + PLATFORM_TOOLS.file, join(cache, PLATFORM_TOOLS.file), PLATFORM_TOOLS.sha1);
  unzip(join(cache, PLATFORM_TOOLS.file), join(cache, 'pt'));
  pt = join(cache, 'pt', 'platform-tools');
  ptOrigin = GOOGLE + PLATFORM_TOOLS.file;
}
mkdirSync(join(dist, 'platform-tools'), { recursive: true });
for (const f of ['adb.exe', 'AdbWinApi.dll', 'AdbWinUsbApi.dll', 'libwinpthread-1.dll', 'NOTICE.txt', 'source.properties']) {
  if (!existsSync(join(pt, f))) die(`platform-tools in ${pt} is missing ${f}`);
  copyFileSync(join(pt, f), join(dist, 'platform-tools', f));
}
const ptVersion = readProp(join(pt, 'source.properties'), 'Pkg.Revision') || 'unknown';

let bt = null;
let btOrigin = '';
if (sdk && existsSync(join(sdk, 'build-tools'))) {
  const byVersion = (a, b) => b.localeCompare(a, 'en', { numeric: true });
  const v = readdirSync(join(sdk, 'build-tools')).sort(byVersion).find((d) => existsSync(join(sdk, 'build-tools', d, 'aapt2.exe')) && existsSync(join(sdk, 'build-tools', d, 'NOTICE.txt')));
  if (v) { bt = join(sdk, 'build-tools', v); btOrigin = `local SDK (${bt})`; }
}
if (!bt) {
  await download(GOOGLE + BUILD_TOOLS.file, join(cache, BUILD_TOOLS.file), BUILD_TOOLS.sha1);
  unzip(join(cache, BUILD_TOOLS.file), join(cache, 'bt'));
  const d = readdirSync(join(cache, 'bt')).map((x) => join(cache, 'bt', x)).find((x) => existsSync(join(x, 'aapt2.exe')));
  if (!d) die(`${BUILD_TOOLS.file} did not contain aapt2.exe`);
  bt = d;
  btOrigin = GOOGLE + BUILD_TOOLS.file;
}
mkdirSync(join(dist, 'tools'), { recursive: true });
for (const f of ['aapt2.exe', 'NOTICE.txt', 'source.properties']) {
  if (!existsSync(join(bt, f))) die(`build-tools in ${bt} is missing ${f}`);
  copyFileSync(join(bt, f), join(dist, 'tools', f));
}
const btVersion = readProp(join(bt, 'source.properties'), 'Pkg.Revision') || 'unknown';

// ------------------------------------------------------------------ 4. package extras
mkdirSync(join(dist, 'data'), { recursive: true });
let iocNote = 'not bundled (--no-iocs); downloaded by the app on first scan';
if (!argv.has('--no-iocs')) {
  const local = join(root, 'data', 'stalkerware.stix2');
  const stix = join(dist, 'data', 'stalkerware.stix2');
  if (existsSync(local)) { copyFileSync(local, stix); iocNote = 'copied from data/stalkerware.stix2'; }
  else {
    const res = await fetch(STIX_URL, { signal: AbortSignal.timeout(120_000) }).catch((e) => die(`could not download the Echap threat list (${e.message}); use --no-iocs to build without it`));
    if (!res.ok) die(`could not download the Echap threat list (HTTP ${res.status}); use --no-iocs to build without it`);
    writeFileSync(stix, Buffer.from(await res.arrayBuffer()));
    iocNote = `downloaded from ${STIX_URL}`;
  }
  JSON.parse(readFileSync(stix, 'utf8')); // must be valid STIX JSON
}
for (const f of ['README.md', 'LICENSE', 'SECURITY.md', 'CHANGELOG.md']) {
  if (!existsSync(join(root, f))) die(`${f} is missing`);
  copyFileSync(join(root, f), join(dist, f));
}
const bunVersion = spawnSync('bun', ['--version'], { encoding: 'utf8', timeout: 30_000 }).stdout?.trim() || 'unknown';
writeFileSync(join(dist, 'THIRD_PARTY_NOTICES.md'), readFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), 'utf8').trimEnd() + `

## Exact versions in this package

| Component | Version | Taken from |
|---|---|---|
| Android SDK Platform-Tools (adb) | ${ptVersion} | ${ptOrigin.replace(root, '.').replace(process.env.LOCALAPPDATA || '\u0000', '%LOCALAPPDATA%')} |
| Android SDK Build-Tools (aapt2) | ${btVersion} | ${btOrigin.replace(root, '.').replace(process.env.LOCALAPPDATA || '\u0000', '%LOCALAPPDATA%')} |
| Bun runtime (inside AndroidGuardian.exe) | ${keptExe ? 'as in the previous build' : bunVersion} | https://bun.sh |
| Echap stalkerware-indicators | ${argv.has('--no-iocs') ? '-' : new Date().toISOString().slice(0, 10)} | ${iocNote} |
`);
copyFileSync(join(root, 'installer', 'install.ps1'), join(dist, 'install.ps1'));
copyFileSync(join(root, 'installer', 'uninstall.ps1'), join(dist, 'uninstall.ps1'));
writeFileSync(join(dist, 'VERSION'), pkg.version + '\n');
// cmd files: CRLF line endings. They leave the program folder before running PowerShell (a cmd window whose
// current directory is the folder would keep it locked), and clear PSModulePath: started from a PowerShell 7
// window, Windows PowerShell 5.1 would inherit 7's module path and fail to load its own cmdlets.
const crlf = (lines) => lines.join('\r\n') + '\r\n';
const winps = '"%SystemRoot%\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"';
writeFileSync(join(dist, 'Install.cmd'), crlf([
  '@echo off',
  'setlocal',
  'title Android Guardian setup',
  'if not exist "%~dp0install.ps1" goto notextracted',
  'set "PSModulePath="',
  'cd /d "%TEMP%"',
  `${winps} -NoProfile -ExecutionPolicy Bypass -File "%~dp0install.ps1" -Local "%~dp0."`,
  'if errorlevel 1 goto failed',
  'echo This window closes by itself in 20 seconds.',
  '"%SystemRoot%\\System32\\timeout.exe" /t 20 >nul 2>&1',
  'exit /b 0',
  ':failed',
  'set rc=%errorlevel%',
  'echo Setup did not finish. Read the message above, then press any key.',
  'pause >nul',
  'exit /b %rc%',
  ':notextracted',
  'echo.',
  'echo Please unzip first.',
  'echo Right-click the downloaded zip file, choose "Extract All...", then open the',
  'echo extracted AndroidGuardian folder and double-click Install.cmd in there.',
  'echo.',
  'pause',
  'exit /b 2',
]));
writeFileSync(join(dist, 'Uninstall.cmd'), crlf([
  '@echo off',
  'title Android Guardian uninstall',
  'set "PSModulePath="',
  'cd /d "%TEMP%"',
  // One line ending in a plain `exit` (which keeps PowerShell's exit code). After the folder and this file are
  // gone, `exit /b` or any further line makes cmd print "The system cannot find the path specified" and exit 1.
  `${winps} -NoProfile -ExecutionPolicy Bypass -File "%~dp0uninstall.ps1" & exit`,
]));

// SHA256SUMS.txt inside the package: every file, so the installer can tell when antivirus removed or altered one.
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
}
const files = walk(dist).sort();
writeFileSync(join(dist, 'SHA256SUMS.txt'), files.map((f) => `${hashFile('sha256', f)}  ${relative(dist, f).split(sep).join('/')}`).join('\n') + '\n');

// Required pieces, checked once more at the end.
for (const f of ['AndroidGuardian.exe', 'platform-tools/adb.exe', 'platform-tools/AdbWinApi.dll', 'platform-tools/AdbWinUsbApi.dll', 'platform-tools/NOTICE.txt', 'tools/aapt2.exe', 'tools/NOTICE.txt', 'install.ps1', 'uninstall.ps1', 'Install.cmd', 'Uninstall.cmd', 'VERSION', 'SHA256SUMS.txt', 'THIRD_PARTY_NOTICES.md', 'LICENSE', 'README.md']) {
  if (!existsSync(join(dist, f))) die(`package is missing ${f}`);
}

// ------------------------------------------------------------------ 5. zip
// A small deterministic zip writer: sorted entries, one fixed timestamp (the last commit time), no extra
// fields. bsdtar and Compress-Archive both store access/creation times, so two identical builds differed.
function writeZip(out, base, top, epochSec) {
  const d = new Date(epochSec * 1000);
  const dosTime = (d.getUTCHours() << 11) | (d.getUTCMinutes() << 5) | (d.getUTCSeconds() >> 1);
  const dosDate = ((d.getUTCFullYear() - 1980) << 9) | ((d.getUTCMonth() + 1) << 5) | d.getUTCDate();
  const entries = [];
  const add = (abs) => {
    const name = relative(base, abs).split(sep).join('/');
    if (statSync(abs).isDirectory()) {
      entries.push({ name: name + '/', data: Buffer.alloc(0), raw: Buffer.alloc(0), method: 0, crc: 0, attr: 0x10 });
      for (const e of readdirSync(abs).sort()) add(join(abs, e));
    } else {
      const raw = readFileSync(abs);
      entries.push({ name, raw, data: deflateRawSync(raw, { level: 9 }), method: 8, crc: crc32(raw), attr: 0x20 });
    }
  };
  add(join(base, top));
  const parts = [];
  const central = [];
  let offset = 0;
  for (const e of entries) {
    const name = Buffer.from(e.name, 'utf8');
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(e.method, 8); local.writeUInt16LE(dosTime, 10); local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(e.crc >>> 0, 14); local.writeUInt32LE(e.data.length, 18); local.writeUInt32LE(e.raw.length, 22);
    local.writeUInt16LE(name.length, 26); local.writeUInt16LE(0, 28);
    parts.push(local, name, e.data);
    const c = Buffer.alloc(46);
    c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(20, 4); c.writeUInt16LE(20, 6); c.writeUInt16LE(0x0800, 8);
    c.writeUInt16LE(e.method, 10); c.writeUInt16LE(dosTime, 12); c.writeUInt16LE(dosDate, 14);
    c.writeUInt32LE(e.crc >>> 0, 16); c.writeUInt32LE(e.data.length, 20); c.writeUInt32LE(e.raw.length, 24);
    c.writeUInt16LE(name.length, 28); c.writeUInt32LE(e.attr, 38); c.writeUInt32LE(offset, 42);
    central.push(c, name);
    offset += 30 + name.length + e.data.length;
  }
  const cdSize = central.reduce((n, b) => n + b.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cdSize, 12); end.writeUInt32LE(offset, 16);
  writeFileSync(out, Buffer.concat([...parts, ...central, end]));
}
const git = spawnSync('git', ['log', '-1', '--format=%ct'], { cwd: root, encoding: 'utf8', timeout: 30_000 });
const epoch = Number(process.env.SOURCE_DATE_EPOCH || (git.status === 0 && git.stdout.trim()) || Math.floor(Date.now() / 1000));
// Same timestamps on the unpacked folder too, so the installer's "keep the newer threat list" check is stable.
for (const f of walk(dist)) utimesSync(f, epoch, epoch);
const zipName = `AndroidGuardian-win64-v${pkg.version}.zip`;
const zip = join(distRoot, zipName);
writeZip(zip, distRoot, 'AndroidGuardian', epoch);
const sha = hashFile('sha256', zip);
writeFileSync(join(distRoot, 'SHA256SUMS.txt'), `${sha}  ${zipName}\n`);

const size = (p) => mb(statSync(p).size);
const total = files.reduce((n, f) => n + statSync(f).size, 0);
console.log(`
Android Guardian ${pkg.version} package
  AndroidGuardian.exe      ${size(exe)}
  platform-tools (adb)     ${ptVersion}, ${mb(walk(join(dist, 'platform-tools')).reduce((n, f) => n + statSync(f).size, 0))}
  tools/aapt2.exe          ${btVersion}, ${size(join(dist, 'tools', 'aapt2.exe'))}
  threat list              ${existsSync(join(dist, 'data', 'stalkerware.stix2')) ? size(join(dist, 'data', 'stalkerware.stix2')) : 'not bundled'}
  folder total             ${mb(total)} in ${files.length} files
  ${zipName}  ${size(zip)}
  sha256 ${sha}
  ${zip}`);
